/**
 * Static basics per destination country (SPEC F-3-3). Only fields I am confident about are filled; an empty field
 * is hidden on the screen. `verifiedAt` is null until a human checks the row against official sources
 * (docs/HUMAN_TODO.md). Visa/entry rules are deliberately NOT stored here: the app only links to official pages.
 */
export interface TimeZoneInfo {
  /** Label shown when a country has several zones. */
  label: string;
  /** IANA time zone. */
  tz: string;
}

export interface CountryInfo {
  /** Representative coordinates (capital or main city) for weather when a trip has no coordinates. */
  lat: number;
  lng: number;
  timezones: TimeZoneInfo[];
  /** ISO 4217 currency code. */
  currency: string;
  languages?: string[];
  voltage?: string;
  frequency?: string;
  plugs?: string[];
  emergency?: { police?: string; ambulance?: string; general?: string };
  verifiedAt: string | null;
}

const z = (tz: string, label = ''): TimeZoneInfo => ({ tz, label });

